pub fn count_special_integers(nums: Vec<i32>) -> i32 {
    let mut seen = vec![0; 101];
    let mut res = 0;
    for w in nums.chunk_by(|a, b| a == b) {
        let i = w[0] as usize;
        seen[i] += 1;
        if seen[i] == 1 {
            res += 1;
        }
        if seen[i] == 2 {
            res -= 1
        }
    }
    res
}

