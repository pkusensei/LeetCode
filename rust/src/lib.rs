pub fn missing_integer(mut nums: Vec<i32>) -> i32 {
    let mut prefix = nums[0];
    for w in nums.windows(2).take_while(|w| w[0] + 1 == w[1]) {
        prefix += w[1];
    }
    nums.sort_unstable();
    while nums.binary_search(&prefix).is_ok() {
        prefix += 1;
    }
    prefix
}

