#[allow(unused_imports)]
use helper::*;

pub fn min_penalty(period: i32, lights: Vec<i32>, arrival_time: Vec<i32>) -> i32 {
    let max = *lights.iter().max().unwrap();
    let mut res = None;
    for t in arrival_time.iter() {
        let r = t % period;
        if r >= max {
            let v = res.get_or_insert(period - r);
            *v = (*v).max(period - r);
        }
    }
    res.unwrap_or(0)
}

