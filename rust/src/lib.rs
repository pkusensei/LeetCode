pub fn count_subarrays(nums: Vec<i32>, min_k: i32, max_k: i32) -> i64 {
    let mut res = 0;
    let mut left = 0;
    let mut res = 0;
    for (right, &num) in nums.iter().enumerate() {
        if num < min_k || num > max_k {
            left = 1 + right;
            continue;
        }
        res += (1 + right - left) as i64
    }
    res
}

