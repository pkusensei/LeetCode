pub fn uniform_array(nums1: Vec<i32>) -> bool {
    let mut min = i32::MAX;
    let mut has_odd = false;
    for &num in nums1.iter() {
        min = min.min(num);
        has_odd |= num & 1 == 1;
    }
    if min & 1 == 1 { true } else { !has_odd }
}

