pub const fn max_product(mut n: i32) -> i32 {
    let [mut d1, mut d2] = [0, 0];
    while n > 0 {
        let d = n % 10;
        n /= 10;
        if d >= d1 {
            d2 = d1;
            d1 = d
        } else if d > d2 {
            d2 = d;
        }
    }
    d1 * d2
}

