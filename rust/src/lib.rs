pub fn create_grid(m: i32, n: i32) -> Vec<String> {
    use std::iter::repeat_n;
    let mut res = Vec::with_capacity(m as usize);
    res.push(repeat_n('.', n as usize).collect());
    for _ in 0..m - 1 {
        let mut v: String = repeat_n('#', n as usize - 1).collect();
        v.push('.');
        res.push(v);
    }
    res
}

