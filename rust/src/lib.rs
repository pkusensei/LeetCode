#[allow(unused_imports)]
use helper::*;

pub fn is_palindromic(s: &str) -> bool {
    let mut res = "".to_string();
    for b in s.bytes() {
        res.push_str(&format!("{:0width$b}", b, width = 10)[2..]);
    }
    is_palindrome(res.bytes())
}

