pub const fn three_fibonacci_sum(n: i32) -> bool {
    if n & 1 == 1 {
        return false;
    }
    let num = n / 2;
    let [mut a, mut b] = [0, 1];
    while a + b < num {
        [a, b] = [b, a + b];
    }
    a + b == num
}

