#[allow(unused_imports)]
use helper::*;

pub fn min_bishop_moves(source: Vec<i32>, target: Vec<i32>) -> i32 {
    let [sx, sy] = source[..] else { unreachable!() };
    let [tx, ty] = target[..] else { unreachable!() };
    if (sx + sy) & 1 != (tx + ty) & 1 {
        -1
    } else if sx + sy == tx + ty || sx - sy == tx - ty {
        1
    } else {
        2
    }
}

