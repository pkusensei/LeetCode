pub fn maximum_product(mut nums: Vec<i32>) -> i32 {
    let n = nums.len();
    nums.sort_unstable();
    let a = nums[n - 3..].iter().product();
    let b = nums[0] * nums[1] * nums[n - 1];
    b.max(a)
}

