pub fn largest_integer(mut n: i32, mut s: i32) -> i32 {
    let mut res = 0;
    while n > 0 {
        let d = s.min(9);
        res = res * 10 + d;
        s -= d;
        n -= 1;
    }
    if s == 0 { res } else { -1 }
}

